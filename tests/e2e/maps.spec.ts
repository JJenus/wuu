import {test,expect,type Page} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
async function open(page:Page,path:string){await page.goto(path);await expect(page.locator('[data-workspace-ready]')).toHaveAttribute('data-workspace-ready','true')}
test('fleet map supports dragging, cursor zoom, keyboard, fit and vehicle/place search',async({page})=>{
  await open(page,'/map')
  const viewport=page.getByRole('region',{name:'Fleet map viewport',exact:true})
  const world=page.locator('.map-canvas')
  const before=await world.getAttribute('style')
  const rect=await viewport.boundingBox()
  await page.mouse.move(rect!.x+80,rect!.y+130)
  await page.mouse.down();await page.mouse.move(rect!.x+190,rect!.y+190);await page.mouse.up()
  await expect(world).not.toHaveAttribute('style',before!)
  await viewport.focus();await page.keyboard.press('ArrowLeft')
  const pan=await world.getAttribute('style')
  await page.mouse.wheel(0,-300)
  await expect(world).not.toHaveAttribute('style',pan!)
  await page.getByRole('button',{name:'Fit visible vehicles',exact:true}).click()
  await page.getByRole('button',{name:'Reset map view',exact:true}).click()
  await expect(world).toHaveAttribute('style',/scale\(1\)/)
  await page.getByRole('searchbox',{name:'Search map'}).fill('CA 7B19K4')
  await page.getByRole('button',{name:'Transit 02 · Vehicle',exact:true}).click()
  await expect(page.getByRole('link',{name:'View Transit 02',exact:true})).toBeVisible()
  await page.getByRole('searchbox',{name:'Search map'}).fill('Dogpatch')
  await page.getByRole('button',{name:'Dogpatch depot · Place',exact:true}).click()
  await expect(page.getByText('Map focused on Dogpatch depot',{exact:true})).toBeVisible()
  await page.getByRole('searchbox',{name:'Search map'}).fill('no such place')
  await expect(page.getByText('No map results found.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Clear map search',exact:true}).click()
  await page.getByRole('button',{name:'Map layers',exact:true}).click()
  await page.getByLabel('Show place labels').uncheck()
  await expect(page.locator('[data-map-labels]')).toHaveCount(0)
})
test('manual navigation releases follow and geofence place search does not edit geometry',async({page})=>{
  await open(page,'/map')
  await page.getByRole('button',{name:'Follow selected vehicle',exact:true}).click()
  const viewport=page.getByRole('region',{name:'Fleet map viewport',exact:true})
  await viewport.focus();await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button',{name:'Follow selected vehicle',exact:true})).toHaveAttribute('aria-pressed','false')
  await open(page,'/geofences/GF-001/edit')
  const before=await page.getByLabel('Center latitude',{exact:true}).inputValue()
  await page.getByRole('searchbox',{name:'Search geofence map'}).fill('Mission')
  await page.getByRole('button',{name:'Mission District · Place',exact:true}).click()
  await expect(page.getByLabel('Center latitude',{exact:true})).toHaveValue(before)
  await expect(page.getByText('No unsaved changes · Resets on reload',{exact:true})).toBeVisible()
})
test('map controls and search work at mobile size and remain accessible in both themes',async({page})=>{
  await page.setViewportSize({width:375,height:1000})
  await open(page,'/map')
  await page.getByRole('searchbox',{name:'Search map'}).fill('SOMA')
  await expect(page.getByRole('button',{name:'SOMA · Place',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
  await page.screenshot({path:'test-results/maps-mobile.png',fullPage:true})
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:'Switch to dark mode'}).click()
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze()).violations).toEqual([])
})

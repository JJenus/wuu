import { test, expect, type Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
async function open(page: Page, path: string) {
  await page.goto(path)
  await expect(page.locator('[data-workspace-ready]')).toHaveAttribute(
    'data-workspace-ready',
    'true',
  )
}
test('create, edit and cancel a circle in the isolated preview', async ({ page }) => {
  await open(page, '/geofences')
  await page.getByRole('link', { name: 'Create geofence' }).click()
  await page.getByRole('button', { name: 'Create preview geofence' }).click()
  await expect(page.locator('#geofence-errors')).toContainText('name')
  await page.getByLabel('Geofence name', { exact: true }).fill('Waterfront depot')
  await page.getByLabel('Assign Transit 01').check()
  await page.getByRole('button', { name: 'Draw circle' }).click()
  await page.getByTestId('geofence-canvas').click({ position: { x: 250, y: 240 } })
  await page.getByLabel('Radius (meters)', { exact: true }).fill('750')
  await page.getByRole('button', { name: 'Create preview geofence' }).click()
  await expect(page.getByRole('heading', { name: 'Waterfront depot', exact: true })).toBeVisible()
  await expect(page.getByText('750 m radius', { exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Edit geofence' }).click()
  await page.getByLabel('Geofence name', { exact: true }).fill('Changed name')
  await page.getByRole('button', { name: 'Cancel editing' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Keep editing' }).click()
  await expect(page.getByLabel('Geofence name', { exact: true })).toHaveValue('Changed name')
  await page.getByRole('button', { name: 'Save preview changes' }).click()
  await expect(page.getByRole('heading', { name: 'Changed name', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Geofence not found' })).toBeVisible()
})
test('polygon drawing, undo, handles, pan, zoom, fit and discard work', async ({ page }) => {
  await open(page, '/geofences/new')
  await page.getByLabel('Geofence name', { exact: true }).fill('Polygon zone')
  await page.getByLabel('Assign Cargo 03').check()
  await page.getByRole('button', { name: 'Draw polygon' }).click()
  const canvas = page.getByTestId('geofence-canvas')
  for (const position of [
    { x: 200, y: 180 },
    { x: 350, y: 180 },
    { x: 350, y: 350 },
    { x: 220, y: 350 },
  ])
    await canvas.click({ position })
  await expect(page.getByLabel('Vertex 4 latitude')).toBeVisible()
  await page.getByRole('button', { name: 'Undo map change' }).click()
  await expect(page.getByLabel('Vertex 4 latitude')).toHaveCount(0)
  await page.getByRole('button', { name: 'Finish polygon' }).click()
  const handle = page.getByRole('button', { name: 'Move vertex 1', exact: true })
  await handle.focus()
  const before = await page.getByLabel('Vertex 1 latitude').inputValue()
  await page.keyboard.press('ArrowUp')
  await expect(page.getByLabel('Vertex 1 latitude')).not.toHaveValue(before)
  const box = await handle.boundingBox()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + 30, box!.y + 30)
  await page.mouse.up()
  await page.getByRole('button', { name: 'Pan map', exact: true }).click()
  const geometryBeforePan = await page.getByLabel('Vertex 1 latitude').inputValue()
  const viewBeforePan = await canvas.getAttribute('data-map-center')
  await canvas.scrollIntoViewIfNeeded()
  const bounds = await canvas.boundingBox()
  await page.mouse.move(bounds!.x + 40, bounds!.y + 40)
  await page.mouse.down()
  await page.mouse.move(bounds!.x + 100, bounds!.y + 70)
  await page.mouse.up()
  await expect(canvas).not.toHaveAttribute('data-map-center', viewBeforePan!)
  await expect(page.getByLabel('Vertex 1 latitude')).toHaveValue(geometryBeforePan)
  const viewBeforeZoom = await canvas.getAttribute('data-map-zoom')
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
  await expect(canvas).not.toHaveAttribute('data-map-zoom', viewBeforeZoom!)
  await page.getByRole('button', { name: 'Fit boundary' }).click()
  await page.getByRole('button', { name: 'Create preview geofence' }).click()
  await expect(page.getByRole('heading', { name: 'Polygon zone', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Edit geofence' }).click()
  await page.getByLabel('Geofence name', { exact: true }).fill('Unsaved')
  await page.getByRole('button', { name: 'Cancel editing' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Discard changes' }).click()
  await expect(page.getByRole('heading', { name: 'Polygon zone', exact: true })).toBeVisible()
})

test('invalid edits never overwrite the saved boundary and navigation asks before discarding', async ({
  page,
}) => {
  await open(page, '/geofences/GF-001/edit')
  await page.getByLabel('Geofence name', { exact: true }).fill('Financial District')
  await page.getByLabel('Radius (meters)', { exact: true }).fill('49')
  await page.getByRole('button', { name: 'Save preview changes' }).click()
  await expect(page.locator('#geofence-errors')).toContainText('already exists')
  await expect(page.locator('#geofence-errors')).toContainText('50 and 5,000')
  await page.getByRole('link', { name: 'Overview', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Keep editing' }).click()
  await expect(page).toHaveURL(/\/geofences\/GF-001\/edit$/)
  await page.getByRole('button', { name: 'Cancel editing' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Discard changes' }).click()
  await expect(page.getByRole('heading', { name: 'Dogpatch depot', exact: true })).toBeVisible()
  await expect(page.getByText('500 m radius', { exact: true })).toBeVisible()
})
test('editor is accessible, responsive, and missing edit IDs fail closed', async ({ page }) => {
  await open(page, '/geofences/missing/edit')
  await expect(page.getByRole('heading', { name: 'Geofence not found' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Save preview changes' })).toHaveCount(0)
  for (const width of [375, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await open(page, '/geofences/GF-001/edit')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.getByLabel('Geofence name', { exact: true })).toHaveValue('Dogpatch depot')
    if (width === 1440) await page.getByRole('button', { name: 'Switch to dark mode' }).click()
    const result = await new AxeBuilder({ page })
      .withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa'])
      .analyze()
    expect(result.violations).toEqual([])
    await page.screenshot({ path: `test-results/geofence-editor-${width}.png`, fullPage: true })
  }
})
